class Conflict(Exception):
    """Duplicate ID with different content, or a duplicate measurement window / collection time."""


def now():
    return datetime.now(timezone.utc)


def iso_now():
    return now().isoformat().replace('+00:00', 'Z')


def ts(value):
    return utc(value).timestamp()


def sha256_file(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def engine_error(exc):
    """The engine raises ValueError for both invalid input and conflicts; split them for HTTP."""
    text = str(exc)
    return Conflict(text) if 'onflicting' in text or 'Duplicate' in text else exc


class Store:
    def __init__(self, db_path):
        self.db_path = str(db_path)
        self.lock = threading.RLock()
        self.db = sqlite3.connect(self.db_path, check_same_thread=False, isolation_level=None)
        self.db.row_factory = sqlite3.Row
        self.db.execute('PRAGMA journal_mode=WAL')
        self.db.execute('PRAGMA foreign_keys=ON')
        self.db.executescript(SCHEMA)
        self.revision = 0
        self.reload()

    # ----- engine view -----
    def reload(self):
        with self.lock:
            engine = MonitoringSupport()
            obs = [json.loads(r[0]) for r in self.db.execute('SELECT observation_json FROM observations')]
            diaries = [json.loads(r[0]) for r in self.db.execute('SELECT diary_json FROM diaries')]
            engine.ingest_many(obs)
            engine.ingest_diaries(diaries)
            self.engine = engine
            self.revision += 1

    def state(self, patient_id, as_of, origin):
        with self.lock:
            return self.engine.state(patient_id, as_of, origin)

    def tx(self):
        return _Tx(self.db)

    # ----- writes -----
    def add_observations(self, observations, lineage=None, import_id=None, actor=None, dataset='api_ingestion'):
        """Atomic batch: the engine validates (types, units, evidence, conflicts) before the DB commit.
        Identical replays are idempotent and return 0 new rows."""
        lineage = lineage or [None] * len(observations)
        with self.lock:
            existing = set(self.engine._observations)  # vendored engine's id index; mirrors the DB
            try:
                parsed = [Observation(**o) if isinstance(o, dict) else _bad(o) for o in observations]
                self.engine.ingest_many(parsed)
            except (TypeError, ValueError) as exc:
                raise engine_error(exc) from exc
            fresh = list({o.observation_id: (o, lin) for o, lin in zip(parsed, lineage)
                          if o.observation_id not in existing}.values())
            try:
                with self.tx() as db:
                    db.executemany('INSERT INTO observations VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)', [
                        (o.observation_id, o.patient_id, o.data_origin, o.channel, o.context, o.device_id,
                         o.source_series_id, o.measurement_start, o.measurement_end, o.available_at,
                         ts(o.measurement_end), ts(o.available_at), json.dumps(asdict(o)),
                         json.dumps(lin) if lin else None, import_id, actor, iso_now()) for o, lin in fresh])
                    _register(db, {(o.patient_id, o.data_origin) for o, _ in fresh}, dataset)
            except sqlite3.IntegrityError as exc:
                self.reload()
                raise Conflict(str(exc)) from exc
            except Exception:
                self.reload()
                raise
            self.revision += 1
            return len(fresh)

    def add_diaries(self, diaries, import_id=None, actor=None, session_id=None, receipt_clock=None, dataset='api_ingestion'):
        with self.lock:
            existing = set(self.engine._diaries)
            try:
                parsed = [SymptomDiary(**d) if isinstance(d, dict) else _bad(d) for d in diaries]
                self.engine.ingest_diaries(parsed)
            except (TypeError, ValueError) as exc:
                raise engine_error(exc) from exc
            fresh, seen = [], set()
            for d in parsed:
                if d.diary_id in existing or d.diary_id in seen:
                    continue
                seen.add(d.diary_id)
                fresh.append(d)
            try:
                with self.tx() as db:
                    db.executemany('INSERT INTO diaries VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?)', [
                        (d.diary_id, d.patient_id, d.data_origin, d.collected_at, d.available_at,
                         ts(d.collected_at), ts(d.available_at), json.dumps(asdict(d)),
                         actor, session_id, receipt_clock, import_id, iso_now()) for d in fresh])
                    _register(db, {(d.patient_id, d.data_origin) for d in fresh}, dataset)
            except sqlite3.IntegrityError as exc:
                self.reload()
                raise Conflict(str(exc)) from exc
            except Exception:
                self.reload()
                raise
            self.revision += 1
            return len(fresh)

    # ----- reads -----
    def patient(self, patient_id, origin):
        return self.db.execute('SELECT * FROM patients WHERE patient_id=? AND data_origin=?', (patient_id, origin)).fetchone()

    def counts(self):
        q = lambda t: self.db.execute(f'SELECT COUNT(*) FROM {t}').fetchone()[0]
        return {t: q(t) for t in ('patients', 'observations', 'diaries', 'recordings', 'scenario_traces', 'notice_acknowledgements')}


class _Tx:
    def __init__(self, db):
        self.db = db

    def __enter__(self):
        self.db.execute('BEGIN IMMEDIATE')
        return self.db

    def __exit__(self, exc_type, *_):
        self.db.execute('ROLLBACK' if exc_type else 'COMMIT')


def _bad(value):
    raise TypeError('Expected a JSON object')


def _register(db, keys, dataset):
    db.executemany('INSERT OR IGNORE INTO patients VALUES (?,?,?,?,?)',
                   [(patient_id, origin, dataset, None, iso_now()) for patient_id, origin in keys])


# ----- imports -----
def _import_record(db, dataset, meta, path, records):
    import_id = 'IMP-' + uuid.uuid4().hex[:12]
    db.execute('INSERT INTO dataset_imports VALUES (?,?,?,?,?,?,?,?,?,?)',
               (import_id, dataset, meta['url'], meta['licence'], meta['attribution'],
                str(Path(path).relative_to(ROOT)), sha256_file(path), 'complete', records, iso_now()))
    return import_id


def imported(store, dataset, path):
    return store.db.execute('SELECT import_id FROM dataset_imports WHERE dataset=? AND file_sha256=?',
                            (dataset, sha256_file(path))).fetchone()


def import_all(store, log=print):
    """Idempotent: each source file is imported once per content hash."""
    if TOLIFE_FILE.exists() and not imported(store, 'tolife', TOLIFE_FILE):
        with gzip.open(TOLIFE_FILE, 'rt') as f:
            wrappers = [json.loads(line) for line in f]
        import_id = 'IMP-' + uuid.uuid4().hex[:12]
        store.add_observations([w['observation'] for w in wrappers], [w['source'] for w in wrappers], import_id, 'import',
                               TOLIFE['source'])
        with store.tx() as db:
            for w in wrappers:  # source-known site from the archive path index/<COUNTRY>/<ID>/...
                parts = w['source']['zip_member'].split('/')
                if len(parts) > 2:
                    db.execute('UPDATE patients SET source_site=? WHERE patient_id=? AND data_origin=?',
                               (parts[1], w['observation']['patient_id'], w['observation']['data_origin']))
            db.execute('INSERT INTO dataset_imports VALUES (?,?,?,?,?,?,?,?,?,?)',
                       (import_id, 'tolife', TOLIFE['url'], TOLIFE['licence'], TOLIFE['attribution'],
                        str(TOLIFE_FILE.relative_to(ROOT)), sha256_file(TOLIFE_FILE), 'complete', len(wrappers), iso_now()))
        log(f'tolife: {len(wrappers)} observations')
    if not imported(store, 'synthetic_example', SYNTHETIC_FILE):
        payload = json.loads(SYNTHETIC_FILE.read_text())
        import_id = 'IMP-' + uuid.uuid4().hex[:12]
        store.add_observations(payload['observations'], None, import_id, 'import', SYNTHETIC['source'])
        store.add_diaries(payload['diaries'], import_id, 'import', receipt_clock='source_file', dataset=SYNTHETIC['source'])
        with store.tx() as db:
            db.execute('INSERT INTO dataset_imports VALUES (?,?,?,?,?,?,?,?,?,?)',
                       (import_id, 'synthetic_example', None, SYNTHETIC['licence'], SYNTHETIC['attribution'],
                        str(SYNTHETIC_FILE.relative_to(ROOT)), sha256_file(SYNTHETIC_FILE), 'complete',
                        len(payload['observations']) + len(payload['diaries']), iso_now()))
        log(f"synthetic example: {len(payload['observations'])} observations, {len(payload['diaries'])} diaries")
    if BIDMC_FILE.exists() and not imported(store, 'bidmc', BIDMC_FILE):
        records = json.loads(BIDMC_FILE.read_text())['records']
        with store.tx() as db:
            import_id = _import_record(db, 'bidmc', BIDMC, BIDMC_FILE, len(records))
            db.executemany('INSERT OR REPLACE INTO recordings VALUES (?,?,?,?,?,?,?,?)', [
                (r['record_id'], 'bidmc', r['source_subject_token'], r['source_file'], r['source_sha256'],
                 'relative_seconds', 480, import_id) for r in records])
        log(f'bidmc: {len(records)} recordings')
    with store.tx() as db:
        db.executemany('INSERT OR IGNORE INTO scenarios VALUES (?,?,?,?)',
                       [(s, role, purpose, PARAMETER_PACKAGE) for s, role, purpose in SCENARIOS])
    if REGISTRY_FILE.exists() and not imported(store, 'tolife_registry', REGISTRY_FILE):
        # Only identity and site. n_exacerbations (outcome) and visit/split metadata are deliberately not read.
        with REGISTRY_FILE.open(newline='') as f:
            rows = [(r['Kit-ID'].strip(), r['Country'].strip()) for r in csv.DictReader(f)]
        with store.tx() as db:
            import_id = _import_record(db, 'tolife_registry', TOLIFE, REGISTRY_FILE, len(rows))
            db.executemany('INSERT OR IGNORE INTO patients VALUES (?,?,?,?,?)',
                           [(pid, 'real_open', TOLIFE['source'], site, iso_now()) for pid, site in rows])
            db.executemany("UPDATE patients SET source_site=? WHERE patient_id=? AND data_origin='real_open' "
                           'AND source_site IS NULL', [(site, pid) for pid, site in rows])
        log(f'tolife registry: {len(rows)} participants')
    if REFERENCE_STATES_FILE.exists() and not imported(store, 'reference_states', REFERENCE_STATES_FILE):
        # Member 2's saved final historical decision per participant: each has its own as_of, none is "now".
        packets = json.loads(REFERENCE_STATES_FILE.read_text())
        with store.tx() as db:
            import_id = _import_record(db, 'reference_states', TOLIFE, REFERENCE_STATES_FILE, len(packets))
            db.executemany('INSERT OR REPLACE INTO reference_decisions VALUES (?,?,?,?,?)', [
                (p['patient_id'], p['data_origin'], p['as_of'], p['schema_version'], import_id) for p in packets])
        log(f'reference decisions: {len(packets)}')
    if not imported(store, 'synthetic_reference_state', SYNTHETIC_STATE_FILE):
        # The fictional example's saved decision time, so it has a final snapshot like the real participants.
        packet = json.loads(SYNTHETIC_STATE_FILE.read_text())
        with store.tx() as db:
            import_id = _import_record(db, 'synthetic_reference_state', SYNTHETIC, SYNTHETIC_STATE_FILE, 1)
            db.execute('INSERT OR REPLACE INTO reference_decisions VALUES (?,?,?,?,?)',
                       (packet['patient_id'], packet['data_origin'], packet['as_of'], packet['schema_version'], import_id))
        log('synthetic reference decision: 1')
    if TRACES_FILE.exists() and not imported(store, 'synthetic_scenario_traces', TRACES_FILE):
        from .sources import import_traces
        # A newer bundled sample supersedes the previous one (same profiles, more observable channels).
        old = [r[0] for r in store.db.execute("SELECT import_id FROM dataset_imports WHERE dataset='synthetic_scenario_traces' "
                                              "AND file_name=? AND status='complete'", (TRACES_FILE.name,))]
        if old:
            with store.tx() as db:
                db.executemany('DELETE FROM scenario_traces WHERE import_id=?', [(i,) for i in old])
                db.executemany("UPDATE dataset_imports SET status='superseded' WHERE import_id=?", [(i,) for i in old])
        log(f'synthetic scenario traces: {import_traces(store, TRACES_FILE)} rows')


